// Writes docs/test-report.md from the end-to-end run (test-results/e2e.json):
//   npm run docs:report   (runs the suite, then this script)
import { readFileSync, writeFileSync } from 'node:fs';
import { arch, cpus, platform, release } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const run = JSON.parse(readFileSync(join(ROOT, 'test-results', 'e2e.json'), 'utf8'));
const { SECURITY_CASES, EXPECTED, PERF_CASES } = await import('../e2e/cases.ts');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const playwright = JSON.parse(readFileSync(join(ROOT, 'node_modules', '@playwright', 'test', 'package.json'), 'utf8'));

/** Every test result: { project, file, title, status, perf } (last retry wins). */
const results = [];
function walk(suite, file) {
  for (const spec of suite.specs ?? []) {
    for (const test of spec.tests) {
      const last = test.results.at(-1);
      const perf = test.annotations?.find((a) => a.type === 'perf')?.description ?? last?.annotations?.find((a) => a.type === 'perf')?.description;
      results.push({
        project: test.projectName,
        file: file ?? suite.file,
        title: [suite.title, spec.title].filter((t) => t && !t.endsWith('.ts')).join(' › '),
        specTitle: spec.title,
        status: test.status === 'skipped' ? 'skipped' : (last?.status ?? 'unknown'),
        perf: perf ? JSON.parse(perf) : null,
      });
    }
  }
  for (const child of suite.suites ?? []) walk(child, file ?? suite.file);
}
for (const suite of run.suites) walk(suite, suite.file);

/** Text for a table cell: raw `<tag>` would be swallowed as HTML, `|` would split the cell. */
const cell = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\|/g, '\\|');

const mark = (status) => ({ passed: '✅ pass', failed: '❌ fail', timedOut: '❌ timeout', skipped: '— n/a', interrupted: '❌' })[status] ?? status;
const find = (project, prefix) => results.find((r) => r.project === project && r.specTitle.startsWith(prefix));
const count = (status) => results.filter((r) => r.status === status).length;
const seconds = (ms) => (ms == null ? '—' : `${(ms / 1000).toFixed(2)} s`);
const date = new Date(run.stats.startTime).toISOString().slice(0, 10);

const lines = [];
const out = (text = '') => lines.push(text);

out('# End-to-end test report');
out();
out(`<!-- Generated by scripts/test-report.mjs (npm run docs:report). Do not edit by hand. -->`);
out();
out('| | |');
out('|---|---|');
out(`| Package | react-llm-markdown ${pkg.version} |`);
out(`| Run | ${date} |`);
out(`| Browser | Chromium (Playwright ${playwright.version}) |`);
out(`| Machine | ${platform()} ${release()} ${arch()}, ${cpus()[0]?.model ?? ''} |`);
out(`| Result | **${count('passed')} passed**, ${count('failed') + count('timedOut')} failed, ${count('skipped')} not applicable |`);
out();
out('Three targets run the same inputs:');
out();
out('- **Web**: `MarkdownView` from `react-llm-markdown`, in the CLI viewer (desktop Chrome viewport).');
out('- **React Native**: `MarkdownView` from `react-llm-markdown/native`, in the [example Expo app](../example/) built for');
out('  the web with react-native-web (Pixel 7 viewport). `react-native-webview` has no web build, so math, Mermaid and');
out('  ECharts show their source here.');
out('- **WebView**: the HTML documents the React Native renderer loads into `react-native-webview` for math, Mermaid');
out('  and ECharts, with their scripts from the pinned CDN (iPhone viewport). "n/a" means the payload has no such block;');
out('  a chart the renderer refuses (SEC-03, SEC-04, SEC-17) never reaches a WebView and shows its source instead.');
out();
out('See [security.md](security.md) for the policies and [performance.md](performance.md) for the method.');
out();

out('## Security');
out();
out('Each payload is rendered, then the test hovers every chart and clicks chart titles, nodes and links. It passes only');
out('if no script ran (`window.__xss` unset), nothing was requested from `evil.example` (the attacker), no dialog');
out('opened, the page did not navigate, and no dangerous element or URL is left in the DOM.');
out();
out('| ID | Payload | Expected | Web | React Native | WebView |');
out('|---|---|---|---|---|---|');
for (const item of SECURITY_CASES) {
  const result = (project) => mark(find(project, `${item.id} `)?.status ?? 'not run');
  out(`| ${item.id} | ${cell(item.title)} | ${EXPECTED[item.id] ?? ''} | ${result('web')} | ${result('native-web')} | ${result('webview')} |`);
}
const regression = (project) => mark(find(project, 'SEC-25')?.status ?? 'not run');
out(`| SEC-25 | Ordinary content after hardening (table, math, currency, Mermaid, charts, sankey) | Renders normally | ${regression('web')} | ${regression('native-web')} | — |`);
out();
out('<details><summary>Payloads</summary>');
out();
for (const item of SECURITY_CASES) {
  const body = item.markdown.length > 700 ? `${item.markdown.slice(0, 700)}\n… (${item.markdown.length.toLocaleString('en')} characters)` : item.markdown;
  out(`**${item.id}** ${cell(item.title)}`);
  out();
  out('````markdown');
  out(body);
  out('````');
  out();
}
out('</details>');
out();

out('## Performance');
out();
out('Budget: the document is rendered within **5 s** and typing into a text field still shows up within **0.5 s**');
out('right after; showing the same answer again must not get slower or keep memory. "Longest task" is the longest');
out('stretch the main thread was busy (a Long Tasks API entry).');
out();
out('| ID | Case | Target | Render | Longest task | Typing | Result |');
out('|---|---|---|---|---|---|---|');
for (const item of PERF_CASES) {
  for (const [project, label] of [['web', 'Web'], ['native-web', 'React Native']]) {
    const r = find(project, `${item.id} `);
    const p = r?.perf ?? {};
    out(`| ${item.id} | ${item.title} | ${label} | ${seconds(p.renderMs)} | ${seconds(p.longestTaskMs)} | ${seconds(p.inputMs)} | ${mark(r?.status ?? 'not run')} |`);
  }
}
for (const [project, label] of [['web', 'Web'], ['native-web', 'React Native']]) {
  const r = find(project, 'PERF-05');
  const p = r?.perf ?? {};
  const timings = (p.timings ?? []).map((t) => seconds(t)).join(', ');
  const heap = (p.heapMb ?? []).join(' → ');
  out(`| PERF-05 | Same answer (200-row table + chart + diagram) 5 times | ${label} | ${timings} | — | heap ${heap} MB | ${mark(r?.status ?? 'not run')} |`);
}
out();

out('## Everything else');
out();
out('| Target | Test | Result |');
out('|---|---|---|');
for (const r of results.filter((r) => !/^(SEC|PERF)-\d/.test(r.specTitle))) {
  const label = { web: 'Web', 'native-web': 'React Native', webview: 'WebView' }[r.project] ?? r.project;
  out(`| ${label} | ${cell(r.title)} | ${mark(r.status)} |`);
}
out();

writeFileSync(join(ROOT, 'docs', 'test-report.md'), `${lines.join('\n')}\n`);
console.log(`wrote docs/test-report.md (${count('passed')} passed, ${count('failed') + count('timedOut')} failed)`);
